import type { CanonicalView, DigitalModel, ManualStep } from '@vitruvius/core';
import { mkdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { getIllustrateProvider } from '../providers/illustrate-provider.js';
import type { IllustrationRequest } from '../providers/illustrate-types.js';
import { getCachedIllustration, illustrateCacheKey, setCachedIllustration } from './cache.js';
import { mergeIllustration } from './merge.js';
import { ILLUSTRATE_STYLE_VERSION } from './style.js';
import type { IllustrateInput, RawIllustration } from './types.js';

/**
 * Pick the base image for a step. With a primed CAD model we lay the schematic out on a
 * canonical view (Compositor-lite); otherwise we redraw the video keyframe (Illustrator).
 * Tier 1 uses the whole-assembly view (or the first available) — per-part / per-step pose
 * alignment is explicitly tier 2 (phase 2).
 */
function pickCanonicalView(model: DigitalModel | null): CanonicalView | null {
	if (!model || model.status !== 'primed' || model.views.length === 0) return null;
	return model.views.find((v) => v.target === 'assembly') ?? model.views[0]!;
}

function planRequest(step: ManualStep, model: DigitalModel | null): IllustrationRequest | null {
	const view = pickCanonicalView(model);
	if (view) return { step, mode: 'compositor-lite', baseImageRef: view.fileRef };
	if (step.keyframeUrl) return { step, mode: 'illustrator', baseImageRef: step.keyframeUrl };
	return null;
}

function extFromMime(mimeType: string): string {
	if (mimeType === 'image/png') return 'png';
	if (mimeType === 'image/webp') return 'webp';
	return 'jpg';
}

async function writeIllustration(outDir: string, raw: RawIllustration): Promise<string> {
	const fileRef = join(outDir, `illustration_${raw.order}.${extFromMime(raw.mimeType)}`);
	await writeFile(fileRef, Buffer.from(raw.imageBase64, 'base64'));
	return fileRef;
}

/**
 * Illustrator agent (spec 14 tier 1): give each critic-reviewed step a print-ready
 * `illustrationUrl`. Generation is cached per step on hash(base image + prompt + style),
 * the provider is called once for the uncached steps, and generated bytes are written to
 * `outDir` as file refs — never inlined in the contract. `keyframeUrl` is preserved as
 * source evidence, and steps the provider declines pass through without an illustration.
 */
export async function illustrateSteps(input: IllustrateInput): Promise<ManualStep[]> {
	if (input.steps.length === 0) return [];

	const model = input.digitalModel ?? null;
	const requests: IllustrationRequest[] = [];
	for (const step of input.steps) {
		const planned = planRequest(step, model);
		if (planned) requests.push(planned);
	}
	if (requests.length === 0) return input.steps;

	const byOrder = new Map<number, RawIllustration>();
	const uncached: IllustrationRequest[] = [];
	for (const req of requests) {
		const cached = getCachedIllustration(illustrateCacheKey(req));
		if (cached) byOrder.set(req.step.order, cached);
		else uncached.push(req);
	}

	if (uncached.length > 0) {
		const provider = getIllustrateProvider();
		const generated = await provider.illustrate(uncached, {
			styleVersion: ILLUSTRATE_STYLE_VERSION,
			manualId: input.manualId
		});
		const genByOrder = new Map(generated.map((g) => [g.order, g]));
		for (const req of uncached) {
			const g = genByOrder.get(req.step.order);
			if (!g) continue; // provider declined this step
			setCachedIllustration(illustrateCacheKey(req), g);
			byOrder.set(req.step.order, g);
		}
	}

	await mkdir(input.outDir, { recursive: true });
	const out: ManualStep[] = [];
	for (const step of input.steps) {
		const raw = byOrder.get(step.order);
		if (!raw) {
			out.push(step);
			continue;
		}
		const fileRef = await writeIllustration(input.outDir, raw);
		out.push(mergeIllustration(step, fileRef));
	}
	return out;
}
